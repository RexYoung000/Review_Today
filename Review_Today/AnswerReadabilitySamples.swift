    | 知识更新代价高 | 重新训练需要计算资源和时间 | 通过更新资料提供新知识 |

    **关键变化：知识可以在回答时被查到，不必全部提前学进模型。**

    ## 一次回答是怎样产生的？

    ~~~mermaid
    flowchart LR
