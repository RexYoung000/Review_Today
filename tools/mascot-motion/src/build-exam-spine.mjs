// Package only the checklist Spine rig into an offline, transparent WebKit
// surface. The exam renderer never loads the Mr. B skeleton.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {root,toolRoot,previewRoot} from './paths.mjs';

const folder=resolve(previewRoot,'entry-icons');
const images={};
for(const name of ['glint','exam-check','exam-line-top','exam-circle','exam-line-bottom'])
 images[name+'.png']='data:image/png;base64,'+(await readFile(resolve(folder,name+'.png'))).toString('base64');
const asset={json:JSON.parse(await readFile(resolve(folder,'entry-icons.json'),'utf8')),
 atlas:await readFile(resolve(folder,'entry-icons.atlas'),'utf8'),images};
const runtime=await readFile(resolve(toolRoot,'node_modules/@esotericsoftware/spine-canvas/dist/iife/spine-canvas.min.js'),'utf8');
const safe=value=>value.replace(/<\/script/gi,'<\\/script');
const player=`
const canvas=document.querySelector('canvas'),ctx=canvas.getContext('2d');
const renderer=new spine.SkeletonRenderer(ctx);renderer.triangleRendering=true;
let rig=null,ready=false,playing=false,dark=false,raf=0,start=0,frames=0,elapsed=0;
const send=type=>window.webkit?.messageHandlers.examMotion?.postMessage({type});
function paint(t){
 const bounds=canvas.getBoundingClientRect(),w=bounds.width,h=bounds.height,d=Math.min(devicePixelRatio||1,2);
 if(canvas.width!==Math.round(w*d)||canvas.height!==Math.round(h*d)){canvas.width=Math.round(w*d);canvas.height=Math.round(h*d);}
 ctx.setTransform(d,0,0,d,0,0);renderer.pixelRatio=d;ctx.clearRect(0,0,w,h);
 canvas.style.filter=dark?'none':'invert(1)';
 if(!rig||!playing)return;
 const s=rig.skeleton;s.setToSetupPose();
 rig.data.findAnimation('exam').apply(s,0,t%2.4,false,[],1,spine.MixBlend.replace,spine.MixDirection.mixIn);
 s.updateWorldTransform(spine.Physics.none);
 ctx.save();ctx.translate(w/2,h/2);const scale=Math.min(w/44,h/44);ctx.scale(scale,-scale);renderer.draw(s);ctx.restore();frames++;
}
function tick(now){raf=0;if(!playing)return;elapsed=(now-start)/1000;paint(elapsed);raf=requestAnimationFrame(tick);}
window.examMotion={
 setState(next){
  dark=!!next.dark;
  if(!!next.playing!==playing){playing=!!next.playing;cancelAnimationFrame(raf);raf=0;
   if(playing){start=performance.now();elapsed=0;raf=requestAnimationFrame(tick);}
   else{start=0;elapsed=0;paint(0);}}
  else if(!playing)paint(0);
 },
 inspect(){return {ready,playing,dark,frames,elapsed,kind:'spine-checklist',hasMascot:false};}
};
new ResizeObserver(()=>paint(elapsed)).observe(canvas);
try{
 const asset=JSON.parse(document.getElementById('rig-data').textContent),atlas=new spine.TextureAtlas(asset.atlas);
 await Promise.all(atlas.pages.map(async page=>{const image=new Image();image.src=asset.images[page.name];await image.decode();page.setTexture(new spine.CanvasTexture(image));}));
 const data=new spine.SkeletonJson(new spine.AtlasAttachmentLoader(atlas)).readSkeletonData(asset.json);
 rig={data,skeleton:new spine.Skeleton(data)};paint(0);ready=true;send('ready');
}catch(error){send('failed');}
`;
const html=`<!doctype html><!-- Generated by tools/mascot-motion/src/build-exam-spine.mjs; do not edit. -->
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; img-src data:; style-src 'unsafe-inline'; connect-src 'none'">
<style>html,body{margin:0;width:100%;height:100%;overflow:hidden;background:transparent}canvas{display:block;width:100%;height:100%;pointer-events:none}</style>
<canvas aria-hidden="true"></canvas>
<script type="application/json" id="rig-data">${safe(JSON.stringify(asset))}</script>
<script>${safe(runtime)}</script><script type="module">${safe(player)}</script>`;
const destination=resolve(root,'Review_Today/ExamEntrySpine.html');
if(process.argv.includes('--check')){
 if(await readFile(destination,'utf8')!==html)throw Error('Exam Spine resource is stale; run build-exam-spine.mjs');
 console.log('Exam Spine resource matches its source.');
}else{
 await writeFile(destination,html);
 console.log(destination,Buffer.byteLength(html),'bytes');
}
